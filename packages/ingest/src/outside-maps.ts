// (Additions to Esther 10:4-16:24, Prayer of Azariah 1-68), because Brenton prints them as lettered
// subverses inside the canonical chapters; only those lettered units (and Greek Daniel 3:24-90) are
// cut, never a canonical verse, which stays addressed under its Hebrew id. A Brenton unit spanning
// several KJV verses sits at the first; the rest are recorded as numbering omissions for LXX.
